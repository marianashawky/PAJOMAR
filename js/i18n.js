  let currentLang = localStorage.getItem(STORAGE_KEY) || 'en';
  const listeners = [];

  function t(key) {
    return translations[currentLang]?.[key] || translations.en[key] || key;
  }

  function getLang() { return currentLang; }

  function isRTL() { return currentLang === 'ar'; }

  function setLang(lang) {
    if (!translations[lang]) return;
    currentLang = lang;
    localStorage.setItem(STORAGE_KEY, lang);
    document.documentElement.lang = lang;
    document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';
    apply();
    listeners.forEach(fn => fn(lang));
  }

  function toggleLang() {
    setLang(currentLang === 'en' ? 'ar' : 'en');
  }

  function apply() {
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      const text = t(key);
      if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
        if (el.hasAttribute('data-i18n-placeholder')) el.placeholder = text;
        else el.value = text;
      } else if (el.tagName === 'OPTION') {
        el.textContent = text;
      } else {
        el.textContent = text;
      }
    });
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
      el.placeholder = t(el.getAttribute('data-i18n-placeholder'));
    });
    document.querySelectorAll('[data-i18n-title]').forEach(el => {
      document.title = t(el.getAttribute('data-i18n-title'));
    });
    document.querySelectorAll('.lang-switch-btn').forEach(btn => {
      const textEl = btn.querySelector('.lang-switch-text');
      if (textEl) textEl.textContent = switchLabel();
      else btn.textContent = switchLabel();
      btn.setAttribute('aria-label', switchAriaLabel());
    });
  }

  function onChange(fn) { listeners.push(fn); }

  function init() {
    document.documentElement.lang = currentLang;
    document.documentElement.dir = isRTL() ? 'rtl' : 'ltr';
    apply();
  }

  function translateValue(enValue) {
    const map = {
      en: {
        'Sheer': 'type.sheer', 'Blackout': 'type.blackout', 'Decorative': 'type.decorative',
        'Classic': 'type.classic', 'Modern': 'type.modern', 'Custom': 'type.custom',
        'Living Room': 'room.livingRoom', 'Bedroom': 'room.bedroom', 'Dining Room': 'room.diningRoom', 'Office': 'room.office',
        'Linen': 'fabric.linen', 'Velvet': 'fabric.velvet', 'Cotton': 'fabric.cotton',
        'Polyester': 'fabric.polyester', 'Premium Blends': 'fabric.premiumBlends',
        'White': 'color.white', 'Beige': 'color.beige', 'Cream': 'color.cream',
        'Grey': 'color.grey', 'Brown': 'color.brown', 'Black': 'color.black', 'Other': 'color.other',
        'Light Filtering': 'light.filtering', 'Room Darkening': 'light.darkening',
        'Minimal': 'style.minimal', 'Luxury': 'style.luxury'
      }
    };
    const key = map.en?.[enValue];
    return key ? t(key) : enValue;
  }

  function tf(key, fallback) {
    return translations[currentLang]?.[key] || translations.en[key] || fallback;
  }

  function fabricI18nKey(id) {
    return id === 'premium-blends' ? 'premiumBlends' : id;
  }

  function translateCollectionName(name) {
    const map = {
      'Modern Collection': 'home.collections.modern',
      'Luxury Collection': 'home.collections.luxury',
      'Natural Collection': 'home.collections.natural',
      'Blackout Collection': 'home.collections.blackout',
      'Classic Collection': 'collection.classic.name'
    };
    const key = map[name];
    return key ? t(key) : name;
  }

  function translateCollection(c) {
    const nameKey = c.id === 'classic' ? 'collection.classic.name' : 'home.collections.' + c.id;
    return {
      name: tf(nameKey, c.name),
      tagline: tf('collection.' + c.id + '.tagline', c.tagline),
      description: tf('collection.' + c.id + '.pageDesc', c.description)
    };
  }

  function translateFabric(f) {
    const k = fabricI18nKey(f.id);
    return {
      name: t('fabric.' + k),
      texture: tf('fabric.' + k + '.texture', f.texture),
      description: tf('fabric.' + k + '.description', f.description)
    };
  }

  function translateProduct(p) {
    const prefix = 'prod.' + p.id;
    return {
      name: tf(prefix + '.name', p.name),
      description: tf(prefix + '.desc', p.description),
      texture: tf(prefix + '.texture', p.texture),
      collection: translateCollectionName(p.collection)
    };
  }

  function translateSpecKey(key) {
    return tf('spec.' + key, key.charAt(0).toUpperCase() + key.slice(1));
  }

